# -*- coding: utf-8 -*-
"""更新《使用说明.txt》：新手势 + 五个设置页。"""
import io

P = '使用说明.txt'
s = io.open(P, encoding='utf-8').read()


def rep(old, new):
    global s
    assert old in s, old[:60]
    s = s.replace(old, new, 1)


rep('''  绕圈       鼠标绕着它画一圈，它会转晕、冒小星星
''',
    '''  绕圈       鼠标绕着它画一圈，它会转晕、冒小星星
  摇一摇     在它身上（身体中段）左右快速摇：它会把脑袋摇起来喊"别摇啦"；
             想让它在这个手势下刷新，设置… -> 手势 -> 打开「摇一摇刷新」
  双下滑     0.9 秒内连着向下划两次，它会开心地弹一下、冒爱心
  长按头顶   按住头顶不动一秒，等于摸头（懒得来回蹭的时候用）
''')

rep('''  偏好   窗口：鼠标穿透 / 显示气泡
         桌面显示：全屏时停用
         卡死急救：卡死自动刷新
  手势   手势互动（鼠标划过时压扁、跳、躲、转圈、摸头）/ 点击说话
  对话   启用 AI / 说话带颜文字 / 清空记忆 / 设置 API Key
''',
    '''  偏好   窗口：鼠标穿透 / 显示气泡
         启动：开机自动启动
         桌面显示：全屏时停用
         卡死急救：卡死自动刷新
  手势   手势互动（鼠标划过时压扁、跳、躲、转圈、摸头）/ 摇一摇刷新 /
         点击说话；下面还写着手势清单
  外观   气泡停留时长（2/4/6/8 秒）/ 动作幅度（安静 / 正常 / 活泼）/
         手势灵敏度（迟钝 / 正常 / 灵敏）
  对话   启用 AI / 说话带颜文字 / 清空记忆 / 设置 API Key
  关于   校徽、版本、素材目录入口
''')

rep('''  * 「手势互动」关掉只是不再**自动**响应鼠标划过；右键 -> 逗它玩 里的动作
    仍然随点随做。
''',
    '''  * 「手势互动」关掉只是不再**自动**响应鼠标划过；右键 -> 逗它玩 里的动作
    仍然随点随做。
  * 「动作幅度」只管划动触发的动作幅度：安静一点适合上班摸鱼，活泼一点
    跳得更高、晃得更明显。
  * 「手势灵敏度」调低以后要划得更快更远才算数（打字时手从屏幕上扫过
    不容易误触发）；调高以后轻轻一带就有反应。
  * 「摇一摇刷新」默认关：摇一摇只是摇头卖萌；打开以后摇一摇等于点一次
    「刷新一下」。
''')

io.open(P, 'w', encoding='utf-8', newline='').write(s)
print('manual updated')
